def sitemap(eps: list[dict]) -> str:
    urls = [f"  <url><loc>{SERIES_URL}</loc><lastmod>{BUILD_DATE}</lastmod></url>"]
    for e in eps:
        lastmod = iso_date(e.get("upload_date")) or BUILD_DATE
        urls.append(f"  <url><loc>{esc(e['page_url'])}</loc><lastmod>{lastmod}</lastmod></url>")
    return ('<?xml version="1.0" encoding="UTF-8"?>\n'
            '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
            + "\n".join(urls) + "\n</urlset>\n")


