def breadcrumb(extra: tuple[str, str] | None = None) -> dict:
    items = [("Home", f"{BASE}/"), ("Microsoft Fabric", FABRIC_URL), ("Fabric Espresso", SERIES_URL)]
    if extra:
        items.append(extra)
    return {"@type": "BreadcrumbList", "itemListElement": [
        {"@type": "ListItem", "position": i, "name": n, "item": u} for i, (n, u) in enumerate(items, 1)]}


def video_object(ep: dict, *, full: bool) -> dict:
    vid = ep["id"]
    desc = plain(ep.get("description") or "")
    obj = {
        "@type": "VideoObject",
        "@id": ep["page_url"] + "#video",
        "name": ep["title"],
        "url": ep["page_url"],
        "description": (short(desc, 2000) if full else ep["meta"]) or ep["meta"],
        "thumbnailUrl": [thumb(vid)],
        "embedUrl": f"https://www.youtube.com/embed/{vid}",
    }
    if iso_date(ep.get("upload_date")):
        obj["uploadDate"] = iso_date(ep["upload_date"])
    if iso_duration(ep.get("duration")):
        obj["duration"] = iso_duration(ep["duration"])
    if not full:
        return obj
    obj["contentUrl"] = watch_url(vid)
    obj["inLanguage"] = "en"
    pub = publisher_for(ep)
    if pub:
        obj["publisher"] = pub
    if ep["role"] == "host":
        obj["author"] = {"@id": PERSON_ID}
        obj["creator"] = {"@id": PERSON_ID}
    elif ep["role"] == "named":
        obj["contributor"] = {"@id": PERSON_ID}
    obj["isPartOf"] = {"@type": "CreativeWorkSeries", "name": "Fabric Espresso", "url": SERIES_URL}
    clips = []
    for c in ep.get("chapters") or []:
        if c.get("start") is None or not c.get("title"):
            continue
        clip = {"@type": "Clip", "name": c["title"], "startOffset": int(c["start"]),
                "url": watch_url(vid, c["start"] or None)}
        if c.get("end") is not None:
            clip["endOffset"] = int(c["end"])
        clips.append(clip)
    if clips:
        obj["hasPart"] = clips
    return obj


def credit_line(ep: dict) -> str:
    n = ep["number"]
    if ep["role"] == "host":
        return f"Episode {n} of Fabric Espresso, hosted by Dr. Estera Kot."
    if ep["role"] == "named":
        return f"Episode {n} of Fabric Espresso, with Dr. Estera Kot."
    return f"Episode {n} of Fabric Espresso, {SERIES_CREDIT}."


