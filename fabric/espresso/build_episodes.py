# ---------------------------------------------------------------- import

def import_dump(full_path: Path, flat_path: Path | None) -> list[dict]:
    full = json.loads(full_path.read_text(encoding="utf-8"))
    entries = [e for e in (full.get("entries") or []) if e]
    out, seen = [], set()
    for e in entries:
        if not e.get("id") or e.get("title") in SKIP_TITLES:
            continue
        seen.add(e["id"])
        out.append({
            "id": e["id"],
            "title": e.get("title") or "",
            "description": e.get("description") or "",
            "upload_date": e.get("upload_date"),
            "timestamp": e.get("timestamp"),
            "duration": e.get("duration"),
            "chapters": [{"start": c.get("start_time"), "end": c.get("end_time"), "title": c.get("title")}
                         for c in (e.get("chapters") or [])],
            "tags": e.get("tags") or [],
            "channel": e.get("channel"),
            "channel_url": e.get("uploader_url") or e.get("channel_url"),
            "playlist_index": e.get("playlist_index"),
        })
    if flat_path:
        flat = json.loads(flat_path.read_text(encoding="utf-8"))
        for i, e in enumerate(flat, 1):
            if e.get("id") in seen or e.get("title") in SKIP_TITLES:
                continue
            out.append({"id": e["id"], "title": e.get("title") or "", "description": "",
                        "upload_date": None, "timestamp": None, "duration": e.get("duration"),
                        "chapters": [], "tags": [], "channel": None, "channel_url": None,
                        "playlist_index": i})
    SOURCE.write_text(json.dumps(out, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    return out


# ---------------------------------------------------------------- helpers

def esc(s: str) -> str:
    return html.escape(s or "", quote=True)


def ld(obj) -> str:
    text = json.dumps(obj, ensure_ascii=False, indent=2).replace("</", "<\\/")
    return f'<script type="application/ld+json">\n{text}\n</script>'


def mmss(sec) -> str:
    if sec is None:
        return ""
    sec = int(round(sec))
    h, rem = divmod(sec, 3600)
    m, s = divmod(rem, 60)
    return f"{h}:{m:02d}:{s:02d}" if h else f"{m}:{s:02d}"


def iso_duration(sec) -> str | None:
    if sec is None:
        return None
    sec = int(round(sec))
    h, rem = divmod(sec, 3600)
    m, s = divmod(rem, 60)
    out = "PT" + (f"{h}H" if h else "") + (f"{m}M" if m else "") + (f"{s}S" if s or not (h or m) else "")
    return out


def iso_date(yyyymmdd: str | None) -> str | None:
    if not yyyymmdd:
        return None
    return f"{yyyymmdd[:4]}-{yyyymmdd[4:6]}-{yyyymmdd[6:8]}"


def human_date(yyyymmdd: str | None) -> str:
    if not yyyymmdd:
        return ""
    dt = datetime.strptime(yyyymmdd, "%Y%m%d")
    return f"{dt:%b} {dt.day}, {dt.year}"


def month_year(yyyymmdd: str) -> str:
    return f"{datetime.strptime(yyyymmdd, '%Y%m%d'):%B %Y}"


SLUG_TAIL_STOP = {"a", "an", "and", "or", "the", "of", "for", "with", "in", "on", "to",
                  "into", "from", "by", "at", "their"}


def slugify(title: str) -> str:
    s = title.replace("&", " and ")
    s = unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode()
    s = s.lower().replace("'", "")
    s = re.sub(r"[^a-z0-9]+", "-", s).strip("-")
    s = re.sub(r"^fabric-espresso-", "", s)  # the path already says espresso
    if len(s) > 70:
        cut = s[:70]
        if s[70] != "-" and "-" in cut:
            cut = cut[:cut.rfind("-")]
        words = cut.strip("-").split("-")
        while len(words) > 3 and words[-1] in SLUG_TAIL_STOP:
            words.pop()
        s = "-".join(words)
    return s.strip("-") or "episode"


def plain(text: str) -> str:
    """Description text for meta tags and JSON-LD: no emoji, no em dashes, one line."""
    out = []
    for ch in text or "":
        cp = ord(ch)
        if ch in "️‍" or unicodedata.category(ch) in ("So", "Cs", "Co") or 0x1F000 <= cp <= 0x1FAFF:
            continue
        out.append(ch)
    s = "".join(out).replace(" ", " ")
    s = re.sub(r"\s*—\s*", ", ", s)
    return re.sub(r"\s+", " ", s).strip()


def short(text: str, limit: int = 155) -> str:
    if len(text) <= limit:
        return text
    cut = text[:limit]
    end = max(cut.rfind(". "), cut.rfind("? "), cut.rfind("! "))
    if end >= 90:
        return cut[:end + 1]
    cut = text[:limit - 3]
    cut = cut[:cut.rfind(" ")] if " " in cut else cut
    return cut.rstrip(" ,;:-") + "..."


URL_RE = re.compile(r"https?://[^\s<>\"']+")


def linkify(line: str) -> str:
    parts, pos = [], 0
    for m in URL_RE.finditer(line):
        url, trail = m.group(0), ""
        while url and url[-1] in ".,;:!?)]}":
            trail, url = url[-1] + trail, url[:-1]
        parts.append(esc(line[pos:m.start()]))
        parts.append(f'<a href="{esc(url)}" rel="nofollow noopener">{esc(url)}</a>{esc(trail)}')
        pos = m.end()
    parts.append(esc(line[pos:]))
    return "".join(parts)


def description_html(desc: str) -> str:
    text = (desc or "").replace("\r\n", "\n").replace(" ", " ")
    blocks = []
    for para in re.split(r"\n\s*\n", text):
        lines = [ln.strip() for ln in para.split("\n") if ln.strip()]
        if lines:
            blocks.append("<p>" + "<br>\n".join(linkify(ln) for ln in lines) + "</p>")
    return "\n      ".join(blocks)


def watch_url(vid: str, t: float | None = None) -> str:
    u = f"https://www.youtube.com/watch?v={vid}"
    return f"{u}&t={int(t)}s" if t else u


def thumb(vid: str) -> str:
    return f"https://i.ytimg.com/vi/{vid}/hqdefault.jpg"


def topic_for(ep: dict) -> str:
    t = ep["title"].lower()
    d = (ep.get("description") or "").lower()
    for key, pat in TITLE_RULES[:3]:
        if re.search(pat, t):
            return key
    if DW_SERIES in d:
        return "Warehouse"
    for key, pat in TITLE_RULES[3:]:
        if re.search(pat, t):
            return key
    return "Other"


def role_for(ep: dict) -> str:
    d = ep.get("description") or ""
    if HOST_RE.search(d):
        return "host"
    if NAMED_RE.search(d):
        return "named"
    return "none"


def person_stub() -> dict:
    return {"@type": "Person", "@id": PERSON_ID, "name": "Estera Kot",
            "honorificPrefix": "Dr.", "url": f"{BASE}/"}


def publisher_for(ep: dict) -> dict | None:
    if PUBLISHER_OVERRIDE:
        return dict(PUBLISHER_OVERRIDE)
    if not ep.get("channel"):
        return None
    pub = {"@type": "Organization", "name": ep["channel"]}
    if ep.get("channel_url"):
        pub["url"] = ep["channel_url"]
    return pub


# ---------------------------------------------------------------- model

def prepare(raw: list[dict]) -> list[dict]:
    eps = [dict(e) for e in raw if e.get("title") not in SKIP_TITLES]
    eps.sort(key=lambda e: (e.get("upload_date") or "99999999", e.get("timestamp") or 0,
                            -(e.get("playlist_index") or 0)))
    used: dict[str, int] = {}
    for n, ep in enumerate(eps, 1):
        ep["number"] = n
        ep["topic"] = topic_for(ep)
        ep["role"] = role_for(ep)
        base = slugify(ep["title"])
        used[base] = used.get(base, 0) + 1
        if used[base] == 1:
            ep["slug"] = base
        else:
            suffix = f"-{used[base]}"
            ep["slug"] = base[:70 - len(suffix)].rstrip("-") + suffix
        ep["page_url"] = f"{SERIES_URL}{ep['slug']}/"
        ep["meta"] = short(plain(ep.get("description") or "")) or (
            f"Fabric Espresso episode: {plain(ep['title'])}. Part of {SERIES_CREDIT}.")
    by_title: dict[str, list[dict]] = {}
    for ep in eps:
        by_title.setdefault(ep["title"], []).append(ep)
    for ep in eps:
        ep["same_title"] = [o for o in by_title[ep["title"]] if o is not ep]
    return eps


