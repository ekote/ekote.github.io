def build(eps: list[dict]) -> None:
    slugs = {e["slug"] for e in eps}
    for child in HERE.iterdir():
        page = child / "index.html"
        if child.is_dir() and child.name not in slugs and page.exists() and MARKER in page.read_text(encoding="utf-8"):
            shutil.rmtree(child)
    for i, ep in enumerate(eps):
        prev = eps[i - 1] if i > 0 else None
        nxt = eps[i + 1] if i + 1 < len(eps) else None
        out = HERE / ep["slug"]
        out.mkdir(exist_ok=True)
        (out / "index.html").write_text(episode_page(ep, prev, nxt), encoding="utf-8")
    (HERE / "index.html").write_text(index_page(eps), encoding="utf-8")
    clean = [{"number": e["number"], "slug": e["slug"], "id": e["id"], "title": e["title"],
              "duration": e.get("duration"), "upload_date": iso_date(e.get("upload_date")),
              "topic": e["topic"]} for e in eps]
    (HERE / "episodes.json").write_text(json.dumps(clean, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    (HERE / "sitemap-espresso.xml").write_text(sitemap(eps), encoding="utf-8")


LD_RE = re.compile(r'<script type="application/ld\+json">(.*?)</script>', re.S)
HREF_RE = re.compile(r'href="([^"]+)"')


def validate(eps: list[dict]) -> list[str]:
    errors, blocks = [], 0
    pages = [HERE / "index.html"] + [HERE / e["slug"] / "index.html" for e in eps]
    for p in pages:
        text = p.read_text(encoding="utf-8")
        found = LD_RE.findall(text)
        if not found:
            errors.append(f"{p.relative_to(HERE)}: no JSON-LD")
        for b in found:
            blocks += 1
            try:
                json.loads(b)
            except json.JSONDecodeError as exc:
                errors.append(f"{p.relative_to(HERE)}: JSON-LD does not parse: {exc}")
        for href in HREF_RE.findall(text):
            if re.match(r"^(https?:|mailto:|#)", href):
                continue
            target = (p.parent / html.unescape(href).split("#")[0].split("?")[0]).resolve()
            if HERE in target.parents or target == HERE:
                if target.is_dir():
                    target = target / "index.html"
                if not target.exists():
                    errors.append(f"{p.relative_to(HERE)}: broken link {href}")
    index = (HERE / "index.html").read_text(encoding="utf-8")
    for e in eps:
        if f'href="{e["slug"]}/"' not in index:
            errors.append(f"index.html does not link {e['slug']}/")
        page = (HERE / e["slug"] / "index.html").read_text(encoding="utf-8")
        if 'href="../"' not in page:
            errors.append(f"{e['slug']}/index.html does not link back to the index")
    dirs = [d for d in HERE.iterdir() if d.is_dir() and (d / "index.html").exists()]
    if len(dirs) != len(eps):
        errors.append(f"{len(dirs)} episode folders for {len(eps)} episodes")
    if len({e["slug"] for e in eps}) != len(eps):
        errors.append("duplicate slugs")
    print(f"validated {len(pages)} pages, {blocks} JSON-LD blocks")
    return errors


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--import", dest="full", type=Path, help="yt-dlp -J playlist dump")
